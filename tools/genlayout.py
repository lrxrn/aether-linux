#!/usr/bin/env python3
"""Generate a Go key-layout table for one VOICSKY model from Aether's JS bundle.

  npx prettier --parser babel LoadingScreen-*.js > bundle.pretty.js     # file from https://aether.voicsky.com/_nuxt/
  python3 tools/genlayout.py bundle.pretty.js pulse96 > layout_pulse96.go

Emits slot, x (px), row, w, h, label and HID usage per key. Labels are Aether's own names: shorten them by hand if they
do not fit the TUI (a key is ~5 columns wide).
"""
import re, sys

src, model = open(sys.argv[1]).read(), sys.argv[2]

def block(marker):
    i = src.find(marker)
    if i < 0:
        sys.exit(f"{model}: '{marker.strip()}' not found (model id right? bundle prettified?)")
    j = src.index("\n    },", i)
    return src[i:j]

layout = block(f"\n    {model}: {{\n      id: `{model}`,\n      unit:")
keys = block(f"\n    {model}: {{\n      id: `{model}`,\n      keyList:")
names = {int(v): n for n, v in re.findall(r"name: `([^`]*)`, value: (\d+)", keys)}
usage = {int(v): int(c) for c, v in re.findall(r"keyCode: (\d+), name: `[^`]*`, value: (\d+)", keys)}

print("package main\n\n// generated by tools/genlayout.py\n")
print("type Key struct {\n\tSlot, X, Row, W, H int\n\tLabel string\n\tUsage int\n}\n\nvar Keys = []Key{")
gutter = int(re.search(r"gutter: (\d+)", layout)[1])
rows = re.split(r"\n\s+\],?\n", layout)
for r, row in enumerate(rows):
    x = 0
    for m in re.finditer(r"\{ value: (\d+), w: (\d+)(?:, h: (\d+))?", row):
        v, w, h = int(m[1]), int(m[2]), int(m[3] or 56)
        label = names.get(v, str(v)).replace("\\", "\\\\").replace('"', '\\"')
        print(f'\t{{{v}, {x}, {r}, {w}, {h}, "{label}", {usage.get(v, 0)}}},')
        x += w + gutter
print("}")
